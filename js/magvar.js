const EPOCHE = 2025;
const N = 12;
const A = 6378.137, B = 6356.7523142, R0 = 6371.2;

function dezimalJahr(d) {
  const y = d.getUTCFullYear();
  const s = Date.UTC(y, 0, 1), e = Date.UTC(y + 1, 0, 1);
  return y + (d.getTime() - s) / (e - s);
}

/** Deklination in Grad (Ost positiv). lat/lon in Grad, hoeheKm über NN, datum: Date */
export function missweisung(lat, lon, hoeheKm = 0, datum = new Date()) {
  const t = dezimalJahr(datum) - EPOCHE;
  const g = [], h = [];
  for (let n = 0; n <= N; n++) {
    g.push([]); h.push([]);
    for (let m = 0; m <= N; m++) { g[n].push(G[n][m] + t * GT[n][m]); h[n].push(H[n][m] + t * HT[n][m]); }
  }
  const phi = lat * Math.PI / 180, lam = lon * Math.PI / 180;
  const sp = Math.sin(phi), cp = Math.cos(phi);
  const sr = Math.sqrt(A * A * cp * cp + B * B * sp * sp);
  const theta = Math.atan2(cp * (hoeheKm * sr + A * A), sp * (hoeheKm * sr + B * B));
  const r = Math.sqrt(hoeheKm * hoeheKm + 2 * hoeheKm * sr +
    (A ** 4 - (A ** 4 - B ** 4) * sp * sp) / (A * A - (A * A - B * B) * sp * sp));
  const c = Math.cos(theta), s = Math.sin(theta);
  const invS = 1 / (s + (s === 0 ? 1e-8 : 0));
  const P = [], DP = [];
  for (let n = 0; n <= N; n++) { P.push(new Array(N + 1).fill(0)); DP.push(new Array(N + 1).fill(0)); }
  P[0][0] = 1; P[1][1] = s; DP[1][1] = c; P[1][0] = c; DP[1][0] = -s;
  for (let n = 2; n <= N; n++) {
    const k = Math.sqrt((2 * n - 1) / (2 * n));
    P[n][n] = P[n - 1][n - 1] * s * k;
    DP[n][n] = (DP[n - 1][n - 1] * s + P[n - 1][n - 1] * c) * k;
  }
  for (let m = 0; m <= N; m++) {
    for (let n = Math.max(m + 1, 2); n <= N; n++) {
      const r0 = Math.sqrt((n - 1) * (n - 1) - m * m), r1 = 1 / Math.sqrt(n * n - m * m);
      P[n][m] = (P[n - 1][m] * c * (2 * n - 1) - P[n - 2][m] * r0) * r1;
      DP[n][m] = ((DP[n - 1][m] * c - P[n - 1][m] * s) * (2 * n - 1) - DP[n - 2][m] * r0) * r1;
    }
  }
  let BR = 0, BT = 0, BP = 0;
  const f0 = R0 / r;
  let f = f0 * f0;
  for (let n = 1; n <= N; n++) {
    let c1 = 0, c2 = 0, c3 = 0;
    for (let m = 0; m <= n; m++) {
      const cm = Math.cos(m * lam), sm = Math.sin(m * lam);
      const tmp = g[n][m] * cm + h[n][m] * sm;
      c1 += tmp * P[n][m];
      c2 += tmp * DP[n][m];
      c3 += m * (g[n][m] * sm - h[n][m] * cm) * P[n][m];
    }
    f *= f0;
    BR += (n + 1) * c1 * f; BT -= c2 * f; BP += c3 * f * invS;
  }
  const psi = theta - (Math.PI / 2 - phi);
  const x = -BT * Math.cos(psi) - BR * Math.sin(psi);
  const y = BP;
  return (x !== 0 || y !== 0) ? Math.atan2(y, x) * 180 / Math.PI : 0;
}
